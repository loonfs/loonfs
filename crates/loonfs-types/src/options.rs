#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mutation_options_default_to_no_replace_no_preconditions_and_no_commit_settings() {
        let commit = CommitOptions {
            commit_id: None,
            message: None,
            preconditions: Vec::new(),
        };
        assert_eq!(CommitOptions::default(), commit);
        assert_eq!(
            PutFileOptions::default(),
            PutFileOptions {
                behavior: DestinationBehavior::NoReplace,
                commit: commit.clone(),
                expected_inode_id: None,
                expected_revision_no: None,
            }
        );
        assert_eq!(
            AppendFileOptions::default(),
            AppendFileOptions {
                commit: commit.clone(),
                expected_inode_id: None,
                expected_revision_no: None,
            }
        );
        assert_eq!(
            CreateDirectoryOptions::default(),
            CreateDirectoryOptions {
                commit: commit.clone(),
                parents: false,
            }
        );
        assert_eq!(
            DeleteOptions::default(),
            DeleteOptions {
                behavior: DeleteDirectoryBehavior::NonRecursive,
                commit: commit.clone(),
                expected_inode_id: None,
            }
        );
        assert_eq!(
            DeleteByInodeOptions::default(),
            DeleteByInodeOptions {
                behavior: DeleteDirectoryBehavior::NonRecursive,
                commit: commit.clone(),
            }
        );
        assert_eq!(
            MoveOptions::default(),
            MoveOptions {
                behavior: DestinationBehavior::NoReplace,
                commit: commit.clone(),
                expected_destination_inode_id: None,
                expected_destination_revision_no: None,
            }
        );
        assert_eq!(
            CopyOptions::default(),
            CopyOptions {
                behavior: DestinationBehavior::NoReplace,
                commit: commit.clone(),
                expected_destination_inode_id: None,
                expected_destination_revision_no: None,
            }
        );
        assert_eq!(
            UpdateAttributesOptions::default(),
            UpdateAttributesOptions {
                commit: commit.clone(),
                expected_inode_id: None,
                expected_attributes_revision_no: None,
            }
        );
        assert_eq!(
            UpdateAccessOptions::default(),
            UpdateAccessOptions {
                commit,
                expected_inode_id: None,
                expected_access_revision_no: None,
            }
        );
        assert_eq!(
            ForkNamespaceOptions::default(),
            ForkNamespaceOptions { snapshot_id: None }
        );
    }

    #[test]
    fn a_range_header_parses_one_range_and_formats_it_back() {
        let length = |length| NonZeroU64::new(length);
        for (header, start_offset, length) in [
            ("bytes=0-99", 0, length(100)),
            ("bytes=5-5", 5, length(1)),
            ("bytes=1024-", 1024, None),
            ("BYTES=7-8", 7, length(2)),
            (" bytes=0-0 ", 0, length(1)),
            ("bytes=0-18446744073709551615", 0, Some(NonZeroU64::MAX)),
        ] {
            let range = ReadRange::from_range_header(header).expect(header);
            assert_eq!(
                range,
                ReadRange {
                    start_offset,
                    length
                },
                "{header}"
            );
        }
        for range in [
            ReadRange {
                start_offset: 0,
                length: length(100),
            },
            ReadRange {
                start_offset: 1024,
                length: None,
            },
        ] {
            assert_eq!(
                ReadRange::from_range_header(&range.to_range_header()),
                Some(range)
            );
        }
        assert_eq!(
            ReadRange {
                start_offset: 10,
                length: length(5),
            }
            .to_range_header(),
            "bytes=10-14"
        );
    }

    #[test]
    fn a_range_header_other_than_one_range_of_bytes_is_refused() {
        for header in [
            "",
            "bytes=",
            "bytes=-500",
            "bytes=0-99,200-299",
            "bytes=0-99, 200-",
            "bytes=10-9",
            "bytes=+1-2",
            "bytes=1-+2",
            "bytes=a-b",
            "bytes 0-99",
            "items=0-99",
            "bytes=18446744073709551616-",
        ] {
            assert_eq!(ReadRange::from_range_header(header), None, "{header}");
        }
    }

    #[test]
    fn a_range_stops_at_the_end_of_the_file() {
        let range = |start_offset, length| ReadRange {
            start_offset,
            length: NonZeroU64::new(length),
        };
        assert_eq!(range(950, 100).end_offset(1000), Some(1000));
        assert_eq!(range(10, 5).end_offset(1000), Some(15));
        assert_eq!(range(10, 0).end_offset(1000), Some(1000));
        assert_eq!(
            range(u64::MAX - 1, 100).end_offset(u64::MAX),
            Some(u64::MAX)
        );
        assert_eq!(range(999, 1).end_offset(1000), Some(1000));
        assert_eq!(range(1000, 1).end_offset(1000), None);
        assert_eq!(range(0, 0).end_offset(0), None);
    }

    #[test]
    fn read_options_leave_the_consistency_to_the_runtime() {
        assert_eq!(StatOptions::default().at, ReadAt::Live(None));
        assert_eq!(ListOptions::default().at, ReadAt::Live(None));
        assert_eq!(ReadAt::from(None), ReadAt::Live(None));
        assert_eq!(ReadFileOptions::default().at, ReadAt::Live(None));
        assert_eq!(DownloadOptions::default().at, ReadAt::Live(None));
        assert_eq!(DownloadOptions::default().start_offset, 0);
        assert_eq!(ListChangesOptions::default().at, ReadAt::Live(None));
        assert_eq!(ListFileRevisionsOptions::default().consistency, None);
        assert_eq!(ListTrashOptions::default().consistency, None);
    }
}
